-- Creates the three tables from README Part 1-1.
-- Paste into Supabase: SQL Editor -> New query -> Run.

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    user_name text,
    user_grad_year bigint,
    user_tcg_status text,
    user_email text
);

create table if not exists public.projects (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    project_name text,
    project_manager_id bigint references public.users (id),
    project_description text
);

create table if not exists public.associates (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    project_id bigint references public.projects (id),
    associate_id bigint references public.users (id)
);

